#!/usr/bin/env python3
"""Generate Claude discovery files from the canonical .agents content."""
import argparse
from pathlib import Path
import sys
import yaml

ROOT = Path(__file__).resolve().parent.parent
TOOLS = {"read": ["Read"], "search": ["Grep", "Glob"], "write": ["Edit", "Write"], "shell": ["Bash"]}


def claude_content(path: Path, source: str) -> str:
    text = path.read_text(encoding="utf-8")
    if source == "commands":
        return text.replace("\nargument:", "\nargument-hint:").replace("{{arguments}}", "$ARGUMENTS")
    if source == "roles":
        sections = text.split("---", 2)
        metadata = yaml.safe_load(sections[1])
        capabilities = metadata.pop("capabilities", None)
        if not isinstance(capabilities, list) or not capabilities or any(c not in TOOLS for c in capabilities):
            raise ValueError(f"{path.name}: declare supported role capabilities")
        metadata["tools"] = ", ".join(tool for capability in capabilities for tool in TOOLS[capability])
        return "---\n" + yaml.safe_dump(metadata, sort_keys=False).strip() + "\n---" + sections[2]
    return text


def artifacts(root: Path) -> dict[Path, str]:
    result = {root / "CLAUDE.md": "# Claude Code adapter\n\n@AGENTS.md\n\nCanonical instructions live in AGENTS.md and .agents/.\nThis file is generated by scripts/sync_adapters.py.\n"}
    for source, target in (("skills", "skills"), ("commands", "commands"), ("roles", "agents")):
        for path in (root / ".agents" / source).rglob("*"):
            if path.is_file():
                result[root / ".claude" / target / path.relative_to(root / ".agents" / source)] = claude_content(path, source)
    for path in (root / ".agents/hooks").glob("*.sh"):
        if path.stem != "lib":
            result[root / ".claude/hooks" / path.name] = ('#!/usr/bin/env bash\n# Generated Claude adapter; policy lives in .agents/hooks.\n'
                'export SDLC_LEGACY_STATE_DIR="${CLAUDE_PROJECT_DIR:-$PWD}/.claude"\n'
                f'exec python3 "$(dirname "$0")/../../scripts/claude_hook.py" {path.stem}\n')
    result[root / ".claude/hooks/lib.sh"] = '#!/usr/bin/env bash\n# Compatibility path only. Shared policy helpers live in .agents/hooks/lib.sh.\n'
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    expected = artifacts(ROOT)
    for path, text in expected.items():
        if path.exists() and path.read_text(encoding="utf-8") == text:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    # Never delete unknown/user files: require a deliberate migration instead.
    for folder in ("skills", "commands", "agents", "hooks"):
        for path in (ROOT / ".claude" / folder).rglob("*"):
            if path.is_file() and path not in expected:
                stale.append(str(path.relative_to(ROOT)))
    if stale:
        print("Adapter drift: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
